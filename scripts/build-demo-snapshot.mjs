#!/usr/bin/env node
/**
 * Builds the embedded demo database once, at build time.
 *
 * Without this, every serverless instance pays for creating the schema and
 * inserting the whole demo dataset before it can answer a single request —
 * and a low-traffic demo starts new instances constantly, so that cost is
 * paid over and over. Here it is paid once and shipped as a compressed
 * snapshot the instance simply loads.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
const { PGlite } = await import("@electric-sql/pglite");
const { PGLiteSocketServer } = await import("@electric-sql/pglite-socket");
const pg = (await import("pg")).default;
const { PrismaPg } = await import("@prisma/adapter-pg");

const { PrismaClient } = await import("../src/generated/prisma/index.js");
const { SCHEMA_SQL } = await import("../src/server/demo/schema-sql.ts");
const { seedDemoData } = await import("../src/server/demo/seed-data.ts");

const PORT = 55470;

const OUT_DIR = path.resolve(process.cwd(), "src/server/demo/snapshot");

function write(contents) {
  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(path.join(OUT_DIR, "data.ts"), contents);
}

/**
 * The snapshot embeds accounts whose password is written in this file, so it
 * is never built for an environment that serves real users.
 *
 * A real deployment still needs the *module* to exist — `embedded-db.ts`
 * imports it, and the bundler resolves that import whether or not the branch
 * around it can ever run. So the file is written empty rather than skipped:
 * the import resolves, the bundle carries no credentials, and anything that
 * actually tries to load the snapshot fails loudly instead of starting a
 * database full of invented data.
 */
const { allowsDemo, appEnv } = await import("../src/lib/app-env.ts");
if (!allowsDemo()) {
  write(
    `// Generated by scripts/build-demo-snapshot.mjs — do not edit by hand.
// APP_ENV was "${appEnv()}" at build time, so no demonstration data was
// embedded. The export exists only so the import in embedded-db.ts resolves.

export const DEMO_SNAPSHOT_BASE64 = "";
`,
  );
  console.log(
    `→ APP_ENV é "${appEnv()}": snapshot de demonstração não gerado (contas semeadas ` +
      "com senha publicada não entram em bundle de ambiente real).",
  );
  process.exit(0);
}

console.log("→ Criando banco de demonstração…");
const database = await PGlite.create();

const server = new PGLiteSocketServer({ db: database, port: PORT, host: "127.0.0.1" });
await server.start();

const pool = new pg.Pool({
  host: "127.0.0.1",
  port: PORT,
  user: "postgres",
  database: "postgres",
  max: 1,
});

await pool.query(SCHEMA_SQL);
console.log("  schema aplicado");

const client = new PrismaClient({ adapter: new PrismaPg(pool) });
await seedDemoData(client, { password: "vionex123", storage: null });
await client.$disconnect();
console.log("  dados de demonstração criados");

await pool.end();
await server.stop();

const dump = await database.dumpDataDir("gzip");
const bytes = Buffer.from(await dump.arrayBuffer());
await database.close();

// Base64 rather than a binary file: a serverless bundle reliably carries
// modules, not arbitrary assets next to them.
write(
  `// Generated by scripts/build-demo-snapshot.mjs — do not edit by hand.
// A gzipped PGlite data directory holding the seeded demo database.

export const DEMO_SNAPSHOT_BASE64 =
  "${bytes.toString("base64")}";
`,
);

console.log(`✓ snapshot gerado: ${Math.round(bytes.length / 1024)} KB`);
