#!/usr/bin/env node
/**
 * Bundles the migration SQL into a TypeScript module.
 *
 * The embedded demo database applies the schema at runtime, and a serverless
 * bundle cannot be relied on to carry `prisma/migrations/**` as readable
 * files — so the SQL is compiled in as a string instead.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(process.cwd(), "prisma/migrations");
const dirs = readdirSync(root)
  .filter((entry) => /^\d+_/.test(entry))
  .sort();

const sql = dirs
  .map((dir) => {
    const body = readFileSync(path.join(root, dir, "migration.sql"), "utf8").trim();
    return `-- ${dir}\n${body}`;
  })
  .join("\n\n");

const out = `// Generated by scripts/generate-schema-sql.mjs — do not edit by hand.
// Run \`npm run schema:sql\` after adding a migration.

/** Every migration, concatenated in order, for the embedded demo database. */
export const SCHEMA_SQL = ${JSON.stringify(sql)};
`;

writeFileSync(path.resolve(process.cwd(), "src/server/demo/schema-sql.ts"), out);
console.log(`schema-sql.ts gerado a partir de ${dirs.length} migration(s), ${sql.length} bytes`);
